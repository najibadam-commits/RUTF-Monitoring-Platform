// Temporary, clearly-labelled sample Findings for screenshots / training material.
//
// First time: `python make-sample-photos.py` (needs Pillow) generates the placeholder images in
// ./sample-assets/ (git-ignored, deterministic). Then:
//
//   node sample-findings.js create    — 3 "Demo …" accounts + 8 Findings across every workflow status
//   node sample-findings.js photos    — (re)adds the evidence photos + per-stage GPS to existing samples
//   node sample-findings.js remove    — deletes exactly what `create` made (incl. stored images) and fixes only the affected ID counters
//       --dry-run            list what would be removed, change nothing
//       --also CODE[,CODE]   also delete these Findings (e.g. a real test Finding registered while taking screenshots)
//
// Everything is attributed to the demo accounts (never a real person) and located in real
// states/LGAs/wards from the imported data, avoiding Borno so the live State Coordinator's own
// state isn't touched. Inserted directly (no RPCs), so no notifications/emails are triggered.
// Row `updated_at` stays "now" on purpose: a phone that already synced only pulls rows newer than
// its watermark, so back-dating it would hide the samples from an already-installed app.
//
// `create` snapshots issue_id_counters first. `remove` uses that snapshot only as a floor for the
// counter buckets of the Findings it deletes (never a wholesale restore), so the numbering of any real
// Finding registered in between is untouched. Snapshot: .sample-findings-state.json (git-ignored).
